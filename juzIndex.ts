export function getJuzEntriesForRange(fromSurahNumber: number, toSurahNumber: number): JuzSurahEntry[] {
  return JUZ_INDEX.filter(
    (e) => e.surahNumber >= fromSurahNumber && e.surahNumber <= toSurahNumber,
  ).sort((a, b) => a.juz - b.juz || a.surahNumber - b.surahNumber);
}

export function formatAyahRange(entry: JuzSurahEntry): string {
  if (entry.fromAyah === null && entry.toAyah === null) return 'كاملة';
  if (entry.fromAyah === entry.toAyah) return `آية ${entry.fromAyah}`;
  return `آيات ${entry.fromAyah} - ${entry.toAyah}`;
}
